export type WebviewStrings = typeof strings;

export function formatReasoningBlockState(
  state: "streaming" | "partial" | "complete",
  truncated: boolean,
): string {
  const label =
    state === "streaming"
      ? strings.reasoning.streaming
      : state === "partial"
        ? strings.reasoning.partial
        : strings.reasoning.complete;
  return truncated ? `${label}${strings.reasoning.truncatedSuffix}` : label;
}

export function formatCommandStatus(
  status: ToolStateMessage["status"],
  output: { readonly exitCode: number | null; readonly signal: string | null } | undefined,
): string {
  if (status === "pending") return strings.command.status.pending;
  if (status === "running") return strings.command.status.running;
  if (status === "error") return strings.command.status.error;
  if (output === undefined) return strings.command.status.pending;
  if (output.exitCode !== null) return strings.command.status.exitedWith(output.exitCode);
  if (output.signal !== null) return strings.command.status.exitedWith(output.signal);
  return strings.command.status.exited;
}
